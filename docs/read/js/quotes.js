// 日付から1件を選ぶ。同じ日なら何度開いても同じ、翌日には変わる。
// ただ日付で割ると出る回数が偏るので、件数ぶんを1周として、
// 周ごとに順番をかき混ぜた「山札」を作り、その日の位置を引く。
// 1周のあいだ同じものは出ない。
function rng(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6D2B79F5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export function ofDay(date) {
  const d = date || new Date();
  const day = Math.floor(Date.UTC(d.getFullYear(), d.getMonth(), d.getDate()) / 86400000);
  const n = QUOTES.length;
  const cycle = Math.floor(day / n);
  const pos = day - cycle * n;
  const idx = QUOTES.map((_, i) => i);
  const r = rng(Math.imul(cycle, 2654435761) ^ 0x9e3779b9);
  for (let i = n - 1; i > 0; i--) {
    const j = Math.floor(r() * (i + 1));
    const t = idx[i]; idx[i] = idx[j]; idx[j] = t;
  }
  return QUOTES[idx[pos]];
}
